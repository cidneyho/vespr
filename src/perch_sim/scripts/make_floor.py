#!/usr/bin/env python3
"""Generate the perch_floor model: a flat, textured floor for the perch worlds.

Optical flow tracks the floor's texture, so a plain floor makes the flow sensor report
"not moving" whatever the drone does, and PX4 then lets the drone drift away unseen. This
floor is a speckled, rubber-mat-like texture with detail from about 1 cm to 20 cm, which a
flow camera can track from roughly 0.3 to 5 m up.

Writes:
  models/perch_floor/model.sdf, model.config
  models/perch_floor/meshes/floor.obj        one square, UVs repeating the texture every TILE m
  models/perch_floor/materials/textures/floor.jpg   seamless TILE x TILE m texture

Usage: python3 make_floor.py   (then restart the sim)
"""
from pathlib import Path

import numpy as np
from PIL import Image

MODEL_DIR = Path(__file__).resolve().parent.parent / 'models' / 'perch_floor'
SIZE = 200.0        # m, side of the floor
TILE = 1.0          # m covered by one copy of the texture
PIXELS = 512        # texture side, so about 2 mm a pixel
FEATURES = (0.01, 0.2)  # m, smallest and largest detail in the texture
SEED = 7


def texture():
    """Seamless grey noise: random phases, more strength at larger features (1/f)."""
    rng = np.random.default_rng(SEED)
    f = np.fft.fftfreq(PIXELS, d=TILE / PIXELS)  # cycles per metre
    fx, fy = np.meshgrid(f, f)
    freq = np.hypot(fx, fy)
    band = (freq >= 1 / FEATURES[1]) & (freq <= 1 / FEATURES[0])
    amplitude = np.where(band, 1 / np.maximum(freq, 1e-9), 0.0)
    phase = np.exp(2j * np.pi * rng.random((PIXELS, PIXELS)))
    noise = np.real(np.fft.ifft2(amplitude * phase))  # periodic, so it tiles without seams
    noise = (noise - noise.mean()) / noise.std()
    grey = np.clip(0.45 + 0.18 * noise, 0.05, 0.95)  # mid grey with strong contrast
    return Image.fromarray((grey * 255).astype(np.uint8), mode='L')


def obj():
    h, uv = SIZE / 2, SIZE / TILE
    return f'''# perch_floor: one {SIZE:.0f} m square at z = 0, texture repeated every {TILE} m
v {-h} {-h} 0
v {h} {-h} 0
v {h} {h} 0
v {-h} {h} 0
vt 0 0
vt {uv} 0
vt {uv} {uv}
vt 0 {uv}
vn 0 0 1
f 1/1/1 2/2/1 3/3/1
f 1/1/1 3/3/1 4/4/1
'''


SDF = f'''<?xml version="1.0"?>
<!--
  Generated by scripts/make_floor.py. Edit the settings there and rerun it.

  Flat floor with a speckled texture, so optical flow has something to track.
  {SIZE:.0f} m square, texture repeating every {TILE} m with detail from {FEATURES[0] * 100:.0f} to {FEATURES[1] * 100:.0f} cm.
  Static. Collision is an infinite plane at z = 0, as Gazebo's usual ground_plane.
-->
<sdf version="1.9">
  <model name="perch_floor">
    <static>true</static>
    <link name="floor">
      <collision name="collision">
        <geometry><plane><normal>0 0 1</normal><size>{SIZE:.0f} {SIZE:.0f}</size></plane></geometry>
      </collision>
      <visual name="visual">
        <geometry><mesh><uri>model://perch_floor/meshes/floor.obj</uri></mesh></geometry>
        <material>
          <diffuse>1 1 1 1</diffuse>
          <specular>0.05 0.05 0.05 1</specular>
          <pbr>
            <metal>
              <albedo_map>model://perch_floor/materials/textures/floor.jpg</albedo_map>
              <roughness>0.9</roughness>
              <metalness>0</metalness>
            </metal>
          </pbr>
        </material>
      </visual>
    </link>
  </model>
</sdf>
'''

CONFIG = '''<?xml version="1.0"?>
<model>
  <name>perch_floor</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <description>Textured floor for the perch worlds, so optical flow can track. Generated by scripts/make_floor.py.</description>
</model>
'''


def main():
    (MODEL_DIR / 'meshes').mkdir(parents=True, exist_ok=True)
    (MODEL_DIR / 'materials' / 'textures').mkdir(parents=True, exist_ok=True)
    texture().save(MODEL_DIR / 'materials' / 'textures' / 'floor.jpg', quality=90)
    (MODEL_DIR / 'meshes' / 'floor.obj').write_text(obj())
    (MODEL_DIR / 'model.sdf').write_text(SDF)
    (MODEL_DIR / 'model.config').write_text(CONFIG)
    print(f'wrote {MODEL_DIR}')


if __name__ == '__main__':
    main()
